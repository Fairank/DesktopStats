def widget_defaults(kind):
    meta = MODULES[kind]
    return dict(
        kind=kind,
        template=kind if kind in TEMPLATES else "custom",
        enabled=True,
        primary=next(iter(meta["primary"])),
        secondary=next(iter(meta["secondary"])),
        chart=True,
        size=None,
        content=None,
        sensor_bindings={},
        title="",
        show_title=True,
        skin=None,
        **dict.fromkeys(GLASS_DEFAULTS),
        grouped=kind in ("cpu", "gpu", "memory"),
        presentation="auto",
        form="square",
        width=None,
        height=None,
        layout_mode="auto",
        columns=2,
        metric_positions={},
        dock="free",
        layer="desktop",
        screen_target="",
        precision="auto",
        temperature_unit="C",
        network_unit="MBps",
        network_target="auto",
        disk_target="all",
        volume_target="system",
        gpu_target="0",
        storage_target="0",
    )


def from_template(key):
    template = TEMPLATES[key]
    result = widget_defaults(template["kind"])
    result.update(template=key, content=list(template["content"]))
    for field in (
        "presentation",
        "form",
        "layout_mode",
        "width",
        "height",
        "dock",
        "layer",
        "show_title",
        "chart",
    ):
        if field in template:
            result[field] = template[field]
    return result
