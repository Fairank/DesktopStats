"""Generate the bounded QML profile table from reviewed offline fan studies."""
import json
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))


def payload():
    from hardware_fan_profiles import PROFILES
    from hardware_series import SERIES_CATALOG
    allowed=("technology","blades","hub_ratio","hub_tone","outer_ring","group_size","shape","direction","hub_shape","ring_width","tone")
    if set(PROFILES)!={row["id"] for row in SERIES_CATALOG}:
        raise ValueError("Every reviewed GPU design needs explicit fan-profile status")
    result={}
    for key,row in PROFILES.items():
        clean={name:row[name] for name in allowed if name in row}
        if row.get("fans"):
            clean['fans']=[{name:fan[name] for name in allowed if name in fan} for fan in row['fans']]
        result[key]=clean
    return result


def main():
    data=payload()
    text='.pragma library\n\n// Generated by tools/generate_hardware_fan_data.py; no runtime discovery.\nvar profiles = '+json.dumps(data,ensure_ascii=True,sort_keys=True,separators=(',',':'))+'\n'
    path=ROOT/'native/HardwareFanProfileData.js'
    path.write_text(text,encoding='utf-8')
    print(json.dumps(dict(path=str(path),profiles=len(data),bytes=path.stat().st_size)))


if __name__=='__main__':
    main()
