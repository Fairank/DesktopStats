"""Bake reviewed exterior structure into local SVG inputs, without discovery."""
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def main():
    from hardware_board_details import PROFILES, MEMORY_PROFILES, drawing_payload
    from hardware_series import SERIES_CATALOG
    from memory_appearance import SERIES_CATALOG as MEMORY_SERIES
    if set(PROFILES) != {row['id'] for row in SERIES_CATALOG} or set(MEMORY_PROFILES) != {row['id'] for row in MEMORY_SERIES}:
        raise ValueError('Every catalog exterior needs an explicit source/unknown record')
    data = drawing_payload()
    text = '.pragma library\n\n// Generated by tools/generate_hardware_board_data.py; no runtime I/O.\nvar models = ' + json.dumps(data, ensure_ascii=True, sort_keys=True, separators=(',', ':')) + '\n'
    path = ROOT/'native/HardwareBoardProfileData.js'
    path.write_text(text, encoding='utf-8')
    print(json.dumps(dict(models=len(data), bytes=path.stat().st_size)))


if __name__ == '__main__':
    main()
