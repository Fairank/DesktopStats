def records(kind=None):
    """Lazily construct the optional directory; invalid filters do not allocate."""
    if kind is not None and (type(kind) is not str or kind not in ('fitting', 'tubing')):
        return ()
    global _ROWS
    if _ROWS is None:
        _ROWS = tuple(_facts())
    return _ROWS if kind is None else tuple(row for row in _ROWS if row['part_kind'] == kind)


def get_record(identity):
    """Return a detached record; malformed/unknown IDs leave the directory cold."""
    if type(identity) is not str or identity not in IDS:
        return None
    from copy import deepcopy
    return deepcopy(next(row for row in records() if row['id'] == identity))
